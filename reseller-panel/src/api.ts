// ══════════════════════════════════════════════════════
//  USER ACTIONS (only if permitted)
// ══════════════════════════════════════════════════════

export async function deactivateUser(uid: string) {
  await updateDoc(doc(db, "users", uid), {
    status: "deactivated",
    deactivatedAt: new Date().toISOString(),
  });
  await setDoc(doc(db, "users", uid, "features", "flags"), {
    bypass: false, streamerMode: false, formBypass: false, stopNetwork: false,
  });
}

export async function reactivateUser(uid: string) {
  await updateDoc(doc(db, "users", uid), {
    status: "active",
    deactivatedAt: "",
  });
}

export async function suspendUser(uid: string) {
  const userSnap = await getDoc(doc(db, "users", uid));
  const userData = userSnap.data();
  if (userData?.licenseCode) {
    try {
      await updateDoc(doc(db, "licenses", userData.licenseCode), { uid: "", redeemedAt: null });
    } catch {}
  }
  await updateDoc(doc(db, "users", uid), {
    status: "suspended",
    suspendedAt: new Date().toISOString(),
    licensed: false,
    licenseCode: "",
  });
  await setDoc(doc(db, "users", uid, "features", "flags"), {
    bypass: false, streamerMode: false, formBypass: false, stopNetwork: false,
  });
}

export async function unsuspendUser(uid: string) {
  await updateDoc(doc(db, "users", uid), {
    status: "active",
    suspendedAt: "",
  });
}

export async function revokeLicense(uid: string) {
  const userSnap = await getDoc(doc(db, "users", uid));
  const userData = userSnap.data();
  if (userData?.licenseCode) {
    await updateDoc(doc(db, "licenses", userData.licenseCode), { uid: "", redeemedAt: null });
  }
  await updateDoc(doc(db, "users", uid), { licensed: false, licenseCode: "" });
}

