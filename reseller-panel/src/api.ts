export async function triggerFullAccountReset(uid: string) {
  // 1. Revoke license
  const userSnap = await getDoc(doc(db, "users", uid));
  const userData = userSnap.data();
  if (userData?.licenseCode) {
    try {
      await updateDoc(doc(db, "licenses", userData.licenseCode), { uid: "", redeemedAt: null });
    } catch {}
  }

  // 2. Wipe HWID
  try { await deleteDoc(doc(db, "users", uid, "hwid", "data")); } catch {}

  // 3. Reset features
  await setDoc(doc(db, "users", uid, "features", "flags"), {
    bypass: false, streamerMode: false, formBypass: false, stopNetwork: false,
  });

  // 4. Reset user doc
  await updateDoc(doc(db, "users", uid), {
    licensed: false,
    licenseCode: "",
  });
}

// ══════════════════════════════════════════════════════
//  LICENSE GENERATION
// ══════════════════════════════════════════════════════

export async function fetchMyLicenses(generatedCodes: string[]): Promise<License[]> {
  if (generatedCodes.length === 0) return [];

  // Firestore 'in' queries support max 30 items at a time
  const licenses: License[] = [];
  const chunks: string[][] = [];
  for (let i = 0; i < generatedCodes.length; i += 30) {
    chunks.push(generatedCodes.slice(i, i + 30));
  }

  for (const chunk of chunks) {
    const q = query(collection(db, "licenses"), where("__name__", "in", chunk));
    const snap = await getDocs(q);
    snap.forEach(d => {
      const l = d.data();
      licenses.push({ ...l, code: d.id } as License);
    });
  }

  return licenses;
}

export async function generateLicenses(
  resellerId: string,
  count: number,
  plan: "trial" | "permanent",
  prefix: string,
  currentKeysUsed: number,
  currentCodes: string[],
  trialDays?: number,
  kernelAccess: boolean = true,
): Promise<string[]> {
  const codes: string[] = [];
  const batch = writeBatch(db);

  for (let i = 0; i < count; i++) {
    const code = `${prefix}-${randomSegment(4)}-${randomSegment(4)}-${randomSegment(4)}`;
    codes.push(code);
    const data: Record<string, unknown> = {
      active: true,
      uid: "",
      plan,
      createdAt: serverTimestamp(),
      redeemedAt: null,
      generatedBy: resellerId,
      kernelAccess,
    };
    if (plan === "trial" && trialDays) data.trialDays = trialDays;
    batch.set(doc(db, "licenses", code), data);
  }

  await batch.commit();

  // Update own reseller counters (allowed by Firestore rules)
  await updateDoc(doc(db, "resellers", resellerId), {
    keysUsed: currentKeysUsed + count,
    generatedCodes: [...currentCodes, ...codes],
    lastActivity: serverTimestamp(),
  });

  return codes;
}

